#!/usr/bin/env python3
"""Emit the tool / operation / argument inventory straight from the live handler registry (S-14).

Offline and read-only: imports the registry (no server start, no Desktop connection, no bytecode
written) and prints JSON. This is the repo-side port of the skill-verify generator
``~/.claude/scripts/skill-verify/dump_mcp_truth.py`` (same ``tools`` shape, so its output stays a
drop-in ground truth for ``check_refs.py`` L8).

    python tools/dump_tool_inventory.py                    # JSON to stdout
    python tools/dump_tool_inventory.py --out inventory.json
    python tools/dump_tool_inventory.py --ops              # one ``tool.operation`` per line

Per tool: ``ops`` (the ``operation`` / ``batch_operation`` enum), ``object_types``, ``modes`` (the
``mode`` enum, when a tool has one), ``args``, ``deferred`` (rare-op args kept out of tools/list),
``aliases``, ``ignored_legacy`` and ``ops_by_type`` (02: operation lists per object_type).
``tests/test_tool_inventory_drift.py`` uses ``build_inventory()`` to keep the tool reference (Part III
of docs/GUIDE.md) in step with the registry.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import sys
from pathlib import Path
from typing import Any, Dict

sys.dont_write_bytecode = True
os.environ.setdefault("PYTHONDONTWRITEBYTECODE", "1")

REPO = Path(__file__).resolve().parent.parent


def _enum(props: Dict[str, Any], key: str):
    spec = props.get(key)
    if isinstance(spec, dict) and isinstance(spec.get("enum"), list):
        return list(spec["enum"])
    return None


def build_inventory() -> Dict[str, Any]:
    """Return ``{"generated", "repo_version", "tools": {name: {...}}}`` from the live registry."""
    for p in (str(REPO), str(REPO / "src")):
        if p not in sys.path:
            sys.path.insert(0, p)
    from server import arg_aliases
    from server.handlers import register_all_handlers
    from server.registry import HandlerRegistry
    from server.tool_surface import DEFERRED_ARGS

    registry = HandlerRegistry()
    register_all_handlers(registry)
    tools: Dict[str, Any] = {}
    for td in registry.get_all_tools():
        props = (td.input_schema or {}).get("properties", {})
        ops = None
        for key in ("operation", "batch_operation"):
            found = _enum(props, key)
            if found is not None:
                ops = found
        tools[td.name] = {
            "ops": ops,
            "object_types": _enum(props, "object_type"),
            "modes": _enum(props, "mode"),
            "args": sorted(props.keys()),
            "deferred": sorted(DEFERRED_ARGS.get(td.name, [])),
            "aliases": arg_aliases.aliases_for(td.name),
            "ignored_legacy": arg_aliases.IGNORED_LEGACY_ARGS.get(td.name, {}),
            "ops_by_type": td.operations_by_type,
        }
    version = ""
    try:
        from __version__ import __version__ as version  # type: ignore[no-redef]
    except Exception:  # pragma: no cover - version is cosmetic
        pass
    return {
        "generated": datetime.date.today().isoformat(),
        "repo_version": version,
        "note": "Generated by tools/dump_tool_inventory.py from the registry. Do not hand-edit.",
        "tools": tools,
    }


def all_op_names(entry: Dict[str, Any]) -> set:
    """Every operation-like name one tool accepts (operation, object_type, mode, per-type ops)."""
    names: set = set()
    for key in ("ops", "object_types", "modes"):
        names.update(entry.get(key) or [])
    for ops in (entry.get("ops_by_type") or {}).values():
        names.update(ops or [])
    return {n for n in names if isinstance(n, str)}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", help="write JSON here instead of stdout")
    ap.add_argument("--ops", action="store_true", help="print one tool.operation per line")
    args = ap.parse_args()

    os.chdir(REPO)
    inventory = build_inventory()
    if args.ops:
        lines = []
        for name, entry in inventory["tools"].items():
            lines.extend(f"{name}.{op}" for op in sorted(entry.get("ops") or []))
        print("\n".join(lines))
        return 0
    text = json.dumps(inventory, indent=1, default=str) + "\n"
    if args.out:
        with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"{len(inventory['tools'])} tools -> {args.out}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
